#!/bin/bash
# Daily regrouping audit, run by kanji-grouping-audit.timer via
# kanji-grouping-audit.service (owner request 2026-11-07). Regenerates
# docs/grouping_recommendations.md with audit_grouping.py and pushes it only
# when the findings changed, not just the date line. No Claude involved: the
# whole scan takes about 15 seconds.
set -euo pipefail
cd /home/ec2-user/apps/kanji
if [ ! -s /tmp/ids.txt ]; then
    curl -fsSL https://raw.githubusercontent.com/cjkvi/cjkvi-ids/master/ids.txt -o /tmp/ids.txt.part \
        && mv /tmp/ids.txt.part /tmp/ids.txt
fi
echo "=== grouping audit $(date -u +%FT%TZ) ==="
git pull -q --no-rebase
REPORT=docs/grouping_recommendations.md
NEW=$(mktemp)
trap 'rm -f "$NEW"' EXIT
backend/venv/bin/python3 backend/audit_grouping.py --markdown "$NEW"
# Line 3 carries the generation date; ignore it when deciding whether anything changed.
if [ -f "$REPORT" ] && diff -q <(sed 3d "$REPORT") <(sed 3d "$NEW") >/dev/null; then
    echo "no change in findings"
    exit 0
fi
cp "$NEW" "$REPORT"
git add "$REPORT"
git commit -q -m "Grouping audit: $(grep -oE '^\*\*[0-9]+ kanji, [0-9]+ suggestions' "$REPORT" | tr -d '*')

Regenerated by backend/run_grouping_audit.sh (daily timer).

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" -- "$REPORT"
git pull -q --no-rebase
git push -q origin master
echo "pushed $(git log --oneline -1)"
